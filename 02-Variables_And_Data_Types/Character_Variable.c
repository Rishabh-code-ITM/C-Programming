#include <stdio.h>                      // Standard input output library

int main() {                            // Program yahin se start hota hai (main function)
    char grade = 'A';                   // Char variable, ek single character store karta hai (single quotes mein)
    printf("Grade = %c\n", grade);      // %c character print karne ke liye
    printf("ASCII = %d\n", grade);      // %d se us character ki ASCII value print hoti hai
    return 0;                           // Program successfully khatam
}                                       // main function end
