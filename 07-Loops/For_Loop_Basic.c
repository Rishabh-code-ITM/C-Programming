#include <stdio.h>                          // Standard input output library

int main() {                                // Program yahin se start hota hai (main function)
    for (int i = 1; i <= 5; i++) {          // for(start; condition; update): i 1 se 5 tak chalega
        printf("Iteration %d\n", i);        // Har baar i ki value print hogi
    }                                       // for loop end
    return 0;                               // Program successfully khatam
}                                           // main function end
